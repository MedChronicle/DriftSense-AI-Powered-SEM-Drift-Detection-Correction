type DropdownMenuItemProps = React.ComponentProps<
  typeof DropdownMenuPrimitive.Item
> & {
  inset?: boolean;
  variant?: "default" | "destructive";
  /** Leading icon */
  icon?: React.ReactNode;
  /** Shows a spinner and ignores selection */
  loading?: boolean;
};

function DropdownMenuItem({
  className,
  inset,
  variant = "default",
  icon,
  loading = false,
  onSelect,
  children,
  ...props
}: DropdownMenuItemProps) {
  return (
    <DropdownMenuPrimitive.Item
      data-slot="dropdown-menu-item"
      data-inset={inset}
      data-variant={variant}
      aria-busy={loading || undefined}
      onSelect={(event) => {
        if (loading) {
          event.preventDefault();
          return;
        }
        onSelect?.(event);
      }}
      className={cn(
        "focus:bg-accent focus:text-accent-foreground data-[variant=destructive]:text-destructive data-[variant=destructive]:focus:bg-destructive/10 dark:data-[variant=destructive]:focus:bg-destructive/20 data-[variant=destructive]:focus:text-destructive data-[variant=destructive]:*:[svg]:!text-destructive [&_svg:not([class*='text-'])]:text-muted-foreground relative flex cursor-default items-center gap-2 rounded-sm px-2 py-1.5 text-sm outline-hidden select-none data-[disabled]:pointer-events-none data-[disabled]:opacity-50 data-[inset]:pl-8 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        loading && "opacity-70",
        className,
      )}
      {...props}
    >
      {loading ? (
        <Loader2Icon
          aria-hidden="true"
          className="animate-spin motion-reduce:animate-none"
        />
      ) : (
        icon
      )}
      {children}
    </DropdownMenuPrimitive.Item>
  );
}

type DropdownMenuCopyItemProps = Omit<DropdownMenuItemProps, "onSelect"> & {
  /** Text copied to the clipboard */
  value: string;
  onCopied?: () => void;
  onCopyError?: (error: unknown) => void;
};

/** Item that copies `value` to the clipboard when selected */
function DropdownMenuCopyItem({
  value,
  onCopied,
  onCopyError,
  children = "Copy",
  ...props
}: DropdownMenuCopyItemProps) {
  const handleSelect = React.useCallback(async () => {
    try {
      await navigator.clipboard.writeText(value);
      onCopied?.();
    } catch (error) {
      onCopyError?.(error);
    }
  }, [value, onCopied, onCopyError]);

  return (
    <DropdownMenuItem onSelect={handleSelect} {...props}>
      {children}
    </DropdownMenuItem>
  );
}

