interface SidebarRailProps extends React.ComponentProps<"button"> {
  /**
   * Let users drag the rail to change the sidebar width (clamped to the
   * provider's minWidth/maxWidth, saved in a cookie). A plain click still
   * toggles the sidebar. Default: false.
   */
  resizable?: boolean;
}

function SidebarRail({
  className,
  resizable = false,
  onClick,
  onPointerDown,
  onPointerMove,
  onPointerUp,
  onPointerCancel,
  ...props
}: SidebarRailProps) {
  const { toggleSidebar, state, setWidth, setIsResizing, minWidth, maxWidth } =
    useSidebar();

  const dragRef = React.useRef<{
    startX: number;
    moved: boolean;
    side: "left" | "right";
  } | null>(null);
  // A drag ends with a click event; remember it so we don't also toggle.
  const justDraggedRef = React.useRef(false);

  const canResize = resizable && state === "expanded";

  const handlePointerDown = (event: React.PointerEvent<HTMLButtonElement>) => {
    onPointerDown?.(event);
    if (!canResize || event.button !== 0) return;

    const container = event.currentTarget.closest<HTMLElement>("[data-side]");
    dragRef.current = {
      startX: event.clientX,
      moved: false,
      side: container?.dataset.side === "right" ? "right" : "left",
    };
    event.currentTarget.setPointerCapture(event.pointerId);
  };

  const handlePointerMove = (event: React.PointerEvent<HTMLButtonElement>) => {
    onPointerMove?.(event);
    const drag = dragRef.current;
    if (!drag) return;

    // Small movements still count as a click.
    if (!drag.moved) {
      if (Math.abs(event.clientX - drag.startX) < 3) return;
      drag.moved = true;
      setIsResizing(true);
    }

    const next =
      drag.side === "left" ? event.clientX : window.innerWidth - event.clientX;
    setWidth(`${Math.min(maxWidth, Math.max(minWidth, Math.round(next)))}px`);
  };

  const endDrag = () => {
    const drag = dragRef.current;
    dragRef.current = null;
    if (drag?.moved) {
      justDraggedRef.current = true;
      setIsResizing(false);
    }
  };

  return (
    <button
      data-sidebar="rail"
      data-slot="sidebar-rail"
      aria-label="Toggle Sidebar"
      tabIndex={-1}
      onClick={(event) => {
        onClick?.(event);
        if (justDraggedRef.current) {
          justDraggedRef.current = false;
          return;
        }
        toggleSidebar();
      }}
      onPointerDown={handlePointerDown}
      onPointerMove={handlePointerMove}
      onPointerUp={(event) => {
        onPointerUp?.(event);
        endDrag();
      }}
      onPointerCancel={(event) => {
        onPointerCancel?.(event);
        endDrag();
      }}
      title={canResize ? "Drag to resize, click to toggle" : "Toggle Sidebar"}
      className={cn(
        "hover:after:bg-sidebar-border absolute inset-y-0 z-20 hidden w-4 -translate-x-1/2 touch-none transition-all ease-linear group-data-[side=left]:-right-4 group-data-[side=right]:left-0 after:absolute after:inset-y-0 after:left-1/2 after:w-[2px] sm:flex motion-reduce:transition-none",
        "in-data-[side=left]:cursor-w-resize in-data-[side=right]:cursor-e-resize",
        "[[data-side=left][data-state=collapsed]_&]:cursor-e-resize [[data-side=right][data-state=collapsed]_&]:cursor-w-resize",
        "hover:group-data-[collapsible=offcanvas]:bg-sidebar group-data-[collapsible=offcanvas]:translate-x-0 group-data-[collapsible=offcanvas]:after:left-full",
        "[[data-side=left][data-collapsible=offcanvas]_&]:-right-2",
        "[[data-side=right][data-collapsible=offcanvas]_&]:-left-2",
        "group-data-[resizing=true]/sidebar-wrapper:after:bg-sidebar-ring",
        canResize && "cursor-col-resize!",
        className,
      )}
      {...props}
    />
  );
}

